// 1. Helper to load category TS file and return parsed tools array
function loadCategoryTools(fileName) {
  const filePath = path.join(DATA_DIR, fileName);
  if (!fs.existsSync(filePath)) return [];
  let content = fs.readFileSync(filePath, 'utf8');
  content = content.split('\n').filter(line => !line.trim().startsWith('import ')).join('\n');
  content = `const getLogo = (name) => "";\n` + content;
  content = content.replace(/: Tool\[\]/g, '');
  content = content.replace(/export const (c\d+Tools) =/g, 'const $1 =');
  const catNum = fileName.replace('.ts', '');
  const varName = `${catNum}Tools`;
  const evalCode = `${content}\nmodule.exports = { tools: ${varName} };`;
  const m = new module.constructor();
  m.paths = module.paths;
  m._compile(evalCode, filePath);
  return m.exports.tools;
}

